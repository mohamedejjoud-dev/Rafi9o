interface I18nContextValue {
  locale: Locale;
  dir: "ltr" | "rtl";
  setLocale: (l: Locale) => void;
  t: (key: string) => string;
  localeInfo: LocaleInfo;
}

const I18nContext = createContext<I18nContextValue | null>(null);

function applyLocale(l: Locale) {
  const info = LOCALES.find((x) => x.code === l) || LOCALES[0];
  document.documentElement.lang = l === "ary" ? "ar-MA" : l;
  document.documentElement.dir = info.dir;
  if (info.dir === "rtl") {
    document.documentElement.classList.add("font-arabic");
  } else {
    document.documentElement.classList.remove("font-arabic");
  }
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [locale, setLocaleState] = useState<Locale>("fr");
  const [mounted, setMounted] = useState(false);

  useEffect(() => {
    setMounted(true);
    const stored = localStorage.getItem("rafi_locale") as Locale | null;
    if (stored && (["fr", "en", "ar", "ary"] as Locale[]).includes(stored)) {
      setLocaleState(stored);
      applyLocale(stored);
    } else {
      // Detect browser language
      const browserLang = navigator.language.split("-")[0] as Locale;
      if (["fr", "en", "ar", "ary"].includes(browserLang)) {
        setLocaleState(browserLang);
        localStorage.setItem("rafi_locale", browserLang);
        applyLocale(browserLang);
      }
    }
  }, []);

  const setLocale = useCallback((l: Locale) => {
    setLocaleState(l);
    try {
      localStorage.setItem("rafi_locale", l);
    } catch {}
    applyLocale(l);
  }, []);

  useEffect(() => {
    if (!mounted) return;
    applyLocale(locale);
  }, [locale, mounted]);

  const t = useCallback(
    (key: string): string => {
      const result =
        translations[locale]?.[key] ??
        (locale === "ary" ? translations.ar?.[key] : undefined) ??
        translations.en?.[key] ??
        translations.fr?.[key] ??
        key;
      return result;
    },
    [locale]
  );

  const localeInfo = LOCALES.find((x) => x.code === locale) || LOCALES[0];

  return (
    <I18nContext.Provider value={{ locale, dir: localeInfo.dir, setLocale, t, localeInfo }}>
      {children}
    </I18nContext.Provider>
  );
}

export function useI18n() {
  const ctx = useContext(I18nContext);
  if (!ctx) throw new Error("useI18n must be used within I18nProvider");
  return ctx;
}
